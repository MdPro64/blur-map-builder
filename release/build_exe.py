"""
Make the two programs with PyInstaller:
  dist\\Blur Map Builder.exe   (bmb_main.py: the designer + build + first-start setup + updates)
  dist\\Blur Map Tester.exe    (map_tester.py: tiny, standard library only)

Our own modules are NOT frozen: the source tree goes into the exe as plain files (the code finds its folders by
__file__ and runs build.py / model_worker.py as scripts). So PyInstaller would not see what they import - this
script scans every import of our code and hands the standard-library / third-party ones to PyInstaller (_deps.py).

  python release\\build_exe.py            (needs: pip install pyinstaller numpy pillow PyOpenGL pyopengltk)
"""
import ast
import os
import shutil
import subprocess
import sys

MB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.dirname(MB), "_release")
SKIP_DIRS = {"__pycache__", "tracks", "release", "my_routes", "docs", "exe", "backups", "research", ".git"}
SKIP_FILES = {"prof.out", "catalog.json", "amax_dbg.bin", "track_map.py", "map_editor.py", "build_track_old.py",
              "pick_spot.py", "route_edit.py"}
DATA_EXT = {".py", ".json", ".lua", ".txt", ".md"}


def source_files():
    out = []
    for d, dirs, files in os.walk(MB):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS and not x.startswith(".")]
        for f in files:
            if f in SKIP_FILES or os.path.splitext(f)[1].lower() not in DATA_EXT or f.startswith("probe_") \
                    or f.startswith("test_"):
                continue
            out.append(os.path.join(d, f))
    return out


def our_modules(files):
    return {os.path.splitext(os.path.basename(f))[0] for f in files if f.endswith(".py")}


def scan_imports(files, ours):
    names = set()
    for f in files:
        if not f.endswith(".py"):
            continue
        try:
            tree = ast.parse(open(f, encoding="utf-8-sig").read())
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                names.update(a.name for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
                names.add(node.module)
                for a in node.names:                       # from PIL import ImageTk -> PIL.ImageTk
                    names.add(node.module + "." + a.name)
    keep = set()
    for n in names:
        top = n.split(".")[0]
        if top in ours or top in ("bpy", "bmesh", "bpy_extras", "mathutils", "capstone", "lupa", "BlurImportExport"):
            continue
        try:
            __import__(n)
            keep.add(n)
        except Exception:                                  # noqa: BLE001 - "from x import function": not a module
            pass
    return sorted(keep)


def main():
    files = source_files()
    deps = scan_imports(files, our_modules(files))
    stage = os.path.join(OUT, "stage")
    shutil.rmtree(stage, ignore_errors=True)
    os.makedirs(stage)
    with open(os.path.join(stage, "_deps.py"), "w") as f:
        f.write("# generated by release/build_exe.py: what our (unfrozen) source code imports\n")
        for n in deps:
            f.write("import %s  # noqa\n" % n)
    entry = os.path.join(stage, "entry_builder.py")
    open(entry, "w").write("import _deps  # noqa\nimport os, sys, runpy\n"
                           "sys.path.insert(0, sys._MEIPASS)\n"
                           "runpy.run_path(os.path.join(sys._MEIPASS, 'bmb_main.py'), run_name='__main__')\n")
    datas = []
    for f in files:
        rel = os.path.relpath(os.path.dirname(f), MB)
        datas += ["--add-data", "%s%s%s" % (f, os.pathsep, rel)]
    icon = os.path.join(MB, "release", "icon.ico")
    common = ["--noconfirm", "--onefile", "--windowed", "--distpath", os.path.join(OUT, "dist"),
              "--workpath", os.path.join(OUT, "build"), "--specpath", stage] + (["--icon", icon] if os.path.exists(icon) else [])
    collect = []
    for pkg in ("OpenGL", "pyopengltk", "PIL", "numpy"):
        collect += ["--collect-all", pkg]
    print("%d source files, %d imports" % (len(files), len(deps)))
    subprocess.check_call([sys.executable, "-m", "PyInstaller", "--name", "Blur Map Builder", "--paths", stage]
                          + common + collect + datas + [entry])
    # the tester: tiny (standard library only)
    subprocess.check_call([sys.executable, "-m", "PyInstaller", "--name", "Blur Map Tester", "--paths", MB,
                           "--hidden-import", "paths"] + common + [os.path.join(MB, "map_tester.py")])
    print("done:", os.path.join(OUT, "dist"))


if __name__ == "__main__":
    main()
